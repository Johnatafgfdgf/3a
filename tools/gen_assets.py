def png(path,w,h,pix):
    raw=bytearray()
    for y in range(h):
        raw.append(0)
        for x in range(w):
            r,g,b,a=pix[y*w+x]
            raw += bytes((r,g,b,a))
    def chunk(t,d):
        return struct.pack(">I",len(d))+t+d+struct.pack(">I",zlib.crc32(t+d)&0xffffffff)
    data=b"\x89PNG\r\n\x1a\n"
    data+=chunk(b"IHDR",struct.pack(">IIBBBBB",w,h,8,6,0,0,0))
    data+=chunk(b"IDAT",zlib.compress(bytes(raw),9))
    data+=chunk(b"IEND",b"")
    open(path,"wb").write(data)

def canvas(w,h,c):
    return [tuple(c) for _ in range(w*h)]

def rect(p,w,h,x0,y0,x1,y1,c):
    x0=max(0,x0);y0=max(0,y0);x1=min(w,x1);y1=min(h,y1)
    for y in range(y0,y1):
        for x in range(x0,x1):
            p[y*w+x]=tuple(c)

def text(p,w,h,x,y,s,scale=4,c=(255,255,255,255)):
    ox=x
    for ch in s.upper():
        if ch=="\n":
            y += 9*scale; x=ox; continue
        pat=FONT.get(ch,FONT[" "])
        for yy,row in enumerate(pat):
            for xx,v in enumerate(row):
                if v=="1": rect(p,w,h,x+xx*scale,y+yy*scale,x+(xx+1)*scale,y+(yy+1)*scale,c)
        x += 6*scale

def stone_bg(w,h):
    p=canvas(w,h,(44,49,55,255))
    for y in range(0,h,32):
        for x in range(0,w,32):
            v=55+((x*13+y*7)//32)%18
            rect(p,w,h,x+1,y+1,x+31,y+31,(v,v+3,v+5,255))
            rect(p,w,h,x+1,y+1,x+31,y+4,(v+13,v+13,v+13,255))
    return p

